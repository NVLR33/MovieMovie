import { getTableConfig, type AnyPgTable } from 'drizzle-orm/pg-core';

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;
const values = (rows: (string | boolean)[][]) => rows.map(row => `  (${row.map(v => typeof v === 'boolean' ? String(v) : literal(v)).join(', ')})`).join(',\n');
const sqlType = (value: string) => value === 'serial' ? 'integer' : value === 'timestamp' ? 'timestamp without time zone' : value;

/** Structural contract only: no business rows, credentials or production connection. */
export function buildSchemaAudit(tables: AnyPgTable[]) {
  const configs = tables.map(getTableConfig).sort((a, b) => a.name.localeCompare(b.name));
  const expectedTables = configs.map(c => [c.name, c.enableRLS] as (string | boolean)[]);
  const columns = configs.flatMap(c => c.columns.map(col => [c.name, col.name, sqlType(col.getSQLType()), col.notNull, col.hasDefault]));
  const indexes = configs.flatMap(c => c.indexes.map(i => {
    const names = i.config.columns.map(col => { if (!('name' in col) || !col.name) throw new Error('Expression indexes need an explicit audit implementation'); return col.name; });
    return [c.name, i.config.name!, names.join(','), i.config.unique];
  }));
  const keys: string[][] = [];
  for (const c of configs) {
    const primary = c.columns.filter(col => col.primary).map(col => col.name);
    if (primary.length) keys.push([c.name, 'p', primary.join(','), '', '', '']);
    for (const p of c.primaryKeys) keys.push([c.name, 'p', p.columns.map(col => col.name).join(','), '', '', '']);
    for (const col of c.columns.filter(col => col.isUnique)) keys.push([c.name, 'u', col.name, '', '', '']);
    for (const u of c.uniqueConstraints) keys.push([c.name, 'u', u.columns.map(col => col.name).join(','), '', '', '']);
    for (const fk of c.foreignKeys) {
      const ref = fk.reference();
      const action = { cascade: 'c', 'set null': 'n', 'set default': 'd', restrict: 'r', 'no action': 'a' }[fk.onDelete || 'no action'];
      keys.push([c.name, 'f', ref.columns.map(col => col.name).join(','), getTableConfig(ref.foreignTable).name, ref.foreignColumns.map(col => col.name).join(','), action]);
    }
  }
  const checks = configs.flatMap(c => c.checks.map(check => [c.name, check.name]));
  return `-- GENERATED by npm run db:bundle from src/db/schema.ts. Read-only; no user data.
-- Run after 01-upgrade.sql and 02-verify.sql. Every row must be OK.
-- Checks types, nullability, required default presence, PK/unique/FK structure,
-- delete actions, index columns/uniqueness/readiness, named validated CHECKs and required RLS.
-- Does not compare default values/CHECK expressions or audit every existing RLS policy.
WITH expected_tables(table_name, rls) AS (VALUES
${values(expectedTables)}
), expected_columns(table_name, column_name, sql_type, not_null, needs_default) AS (VALUES
${values(columns)}
), expected_indexes(table_name, index_name, columns, is_unique) AS (VALUES
${values(indexes)}
), expected_keys(table_name, key_type, columns, foreign_table, foreign_columns, delete_action) AS (VALUES
${values(keys)}
), expected_checks(table_name, check_name) AS (VALUES
${values(checks)}
), actual_indexes AS (
  SELECT t.relname AS table_name, x.relname AS index_name, i.indisunique, i.indisvalid, i.indisready, i.indpred,
    (SELECT string_agg(a.attname::text, ',' ORDER BY u.ord)
     FROM unnest(i.indkey::smallint[]) WITH ORDINALITY u(attnum,ord)
     JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=u.attnum WHERE u.ord<=i.indnkeyatts) AS columns
  FROM pg_index i JOIN pg_class t ON t.oid=i.indrelid JOIN pg_class x ON x.oid=i.indexrelid
  JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname='public'
), actual_keys AS (
  SELECT t.relname AS table_name, k.contype::text AS key_type, k.convalidated,
    (SELECT string_agg(a.attname::text, ',' ORDER BY u.ord) FROM unnest(k.conkey) WITH ORDINALITY u(attnum,ord)
     JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=u.attnum) AS columns,
    coalesce(ft.relname,'') AS foreign_table, coalesce(fn.nspname,'') AS foreign_schema,
    coalesce((SELECT string_agg(a.attname::text, ',' ORDER BY u.ord) FROM unnest(k.confkey) WITH ORDINALITY u(attnum,ord)
     JOIN pg_attribute a ON a.attrelid=k.confrelid AND a.attnum=u.attnum),'') AS foreign_columns,
    k.confdeltype::text AS delete_action
  FROM pg_constraint k JOIN pg_class t ON t.oid=k.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace
  LEFT JOIN pg_class ft ON ft.oid=k.confrelid LEFT JOIN pg_namespace fn ON fn.oid=ft.relnamespace
  WHERE n.nspname='public' AND k.contype IN ('p','u','f')
), checks(check_name, ok) AS (
  SELECT 'Table: '||e.table_name, EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname=e.table_name AND c.relkind='r') FROM expected_tables e
  UNION ALL
  SELECT 'RLS: '||e.table_name, EXISTS(SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname=e.table_name AND c.relrowsecurity) FROM expected_tables e WHERE e.rls
  UNION ALL
  SELECT 'Column: '||e.table_name||'.'||e.column_name, EXISTS(
    SELECT 1 FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid JOIN pg_namespace n ON n.oid=c.relnamespace
    LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
    WHERE n.nspname='public' AND c.relname=e.table_name AND a.attname=e.column_name AND a.attnum>0 AND NOT a.attisdropped
      AND format_type(a.atttypid,a.atttypmod)=e.sql_type AND a.attnotnull=e.not_null
      AND (NOT e.needs_default OR d.oid IS NOT NULL OR a.attidentity<>'')) FROM expected_columns e
  UNION ALL
  SELECT 'Index: '||e.index_name, EXISTS(SELECT 1 FROM actual_indexes a WHERE a.table_name=e.table_name AND a.index_name=e.index_name AND a.columns=e.columns AND a.indisunique=e.is_unique AND a.indisvalid AND a.indisready AND a.indpred IS NULL) FROM expected_indexes e
  UNION ALL
  SELECT 'Key '||e.key_type||': '||e.table_name||'('||e.columns||')', EXISTS(
    SELECT 1 FROM actual_keys a WHERE a.table_name=e.table_name AND a.key_type=e.key_type AND a.columns=e.columns AND a.convalidated
    AND (e.key_type<>'f' OR (a.foreign_schema='public' AND a.foreign_table=e.foreign_table AND a.foreign_columns=e.foreign_columns AND a.delete_action=e.delete_action))) FROM expected_keys e
  UNION ALL
  SELECT 'CHECK: '||e.check_name, EXISTS(SELECT 1 FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relname=e.table_name AND k.conname=e.check_name AND k.contype='c' AND k.convalidated) FROM expected_checks e
)
SELECT check_name, CASE WHEN ok IS TRUE THEN 'OK' ELSE 'NEEDS ATTENTION' END AS result FROM checks ORDER BY check_name;
`;
}

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export type MigrationFile = { name: string; sql: string; checksum: string };
export const MIGRATION_LOCK = 1808523041;
export const MIGRATION_SETUP = `
CREATE SCHEMA IF NOT EXISTS moviemovie_migrations;
REVOKE ALL ON SCHEMA moviemovie_migrations FROM PUBLIC;
CREATE TABLE IF NOT EXISTS moviemovie_migrations.history (
  name text PRIMARY KEY,
  checksum text NOT NULL,
  applied_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE moviemovie_migrations.history ENABLE ROW LEVEL SECURITY;
`;
export const MIGRATION_PREFLIGHT = `
DO $preflight$
BEGIN
  IF to_regclass('public.mg_users') IS NULL OR to_regclass('public.mg_movies') IS NULL
     OR to_regclass('public.mg_watches') IS NULL OR to_regclass('public.mg_comments') IS NULL THEN
    RAISE EXCEPTION 'MovieMovie baseline tables are missing. Initialize a new database with scripts/setup-db.ts first.';
  END IF;
END
$preflight$;
`;

export function readMigrations(directory: string): MigrationFile[] {
  return readdirSync(directory).filter(name => /^\d{8}-[a-z0-9-]+\.sql$/.test(name)).sort().map(name => {
    const sql = readFileSync(join(directory, name), 'utf8');
    return { name, sql, checksum: createHash('sha256').update(sql).digest('hex') };
  });
}

export function planMigrations(files: readonly MigrationFile[], applied: readonly { name: string; checksum: string }[]) {
  const history = new Map(applied.map(row => [row.name, row.checksum]));
  for (const file of files) {
    const checksum = history.get(file.name);
    if (checksum && checksum !== file.checksum) throw new Error(`Checksum mismatch for ${file.name}. Do not edit applied migrations; add a new migration instead.`);
  }
  return files.filter(file => !history.has(file.name));
}

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`;
export function buildSupabaseBundle(files: readonly MigrationFile[], verificationSql?: string) {
  return `-- GENERATED by npm run db:bundle. Do not edit manually.
-- MovieMovie: upgrade an EXISTING database. Paste the entire file into Supabase SQL Editor.
-- Run as the PostgreSQL table owner (normally postgres). Back up your database first.
-- Atomic/idempotent; no credentials, DROP, TRUNCATE or automatic content seeding.
BEGIN;
SET LOCAL search_path = public, pg_catalog;
SET LOCAL lock_timeout = '15s';
SET LOCAL statement_timeout = '120s';
SELECT pg_advisory_xact_lock(${MIGRATION_LOCK});
${MIGRATION_PREFLIGHT}
${MIGRATION_SETUP}
${files.map(file => {
  const delimiter = `$file_${file.checksum.slice(0, 16)}$`;
  if (file.sql.includes(delimiter)) throw new Error(`SQL delimiter collision: ${file.name}`);
  return `
-- ========== ${file.name} ==========
DO $apply_migration$
BEGIN
  IF EXISTS (SELECT 1 FROM moviemovie_migrations.history WHERE name = ${literal(file.name)} AND checksum <> ${literal(file.checksum)}) THEN
    RAISE EXCEPTION 'Applied migration checksum mismatch: ${file.name}';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM moviemovie_migrations.history WHERE name = ${literal(file.name)}) THEN
    EXECUTE ${delimiter}
${file.sql}
${delimiter};
    INSERT INTO moviemovie_migrations.history(name, checksum)
    VALUES (${literal(file.name)}, ${literal(file.checksum)});
  END IF;
END
$apply_migration$;
`;
}).join('\n')}
${verificationSql ? `
-- Fail closed on incompatible legacy schema before committing any migration.
DO $verify_schema$
DECLARE failed text;
BEGIN
  SELECT left(string_agg(check_name, '; '), 2000) INTO failed FROM (
${verificationSql.trim().replace(/;$/, '')}
  ) readiness WHERE result <> 'OK';
  IF failed IS NOT NULL THEN
    RAISE EXCEPTION 'MovieMovie schema verification failed: %. Run 03-schema-audit.sql for details; no unsafe repair was attempted.', failed;
  END IF;
END
$verify_schema$;
` : ''}
COMMIT;
-- All changes committed successfully. Review the readiness checks in 02-verify.sql.
`;
}
